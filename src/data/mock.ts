function buildAnswers(
  overrides: Partial<Record<string, Partial<Audit['answers'][string]>>> = {},
): Audit['answers'] {
  const allQuestions = mockQuestionnaire.sections.flatMap((s) => s.questions);
  const answers: Audit['answers'] = {};
  for (const q of allQuestions) {
    const o = overrides[q.id];
    answers[q.id] = {
      questionId: q.id,
      status: o?.status ?? null,
      score: o?.score ?? 0,
      weight: q.weight,
      comment: o?.comment ?? '',
      evidences: o?.evidences ?? [],
      flaggedForReview: o?.flaggedForReview ?? false,
      responsibleId: o?.responsibleId,
      dueDate: o?.dueDate,
      actionPlanId: o?.actionPlanId,
      answeredAt: o?.answeredAt,
    };
  }
  return answers;
}

